import { useState, type JSX } from "react";
import {
  Chip,
  CircularProgress,
  MenuItem,
  Paper,
  Stack,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TablePagination,
  TableRow,
  TextField,
  Typography,
} from "@wso2/oxygen-ui";
import ErrorNotice from "@components/error-notice/ErrorNotice";
import { useNdaRecords } from "@features/legal/api/useNdaRecords";
import { periodLabel, periodOptions } from "@features/legal/recordPeriods";

const PAGE_SIZE = 25;

// Entity keys are "WSO2 (UK) Ltd — UK"; shown as on the NDA page's dropdown.
function entityLabel(key: string): string {
  return key.replace(/ \u2014 (\w+)$/, " ($1)");
}

/**
 * Recently generated NDAs, newest first: who generated it, for which counterparty,
 * with which WSO2 entity, and when. Only rendered for the Legal team.
 */
export default function NdaRecordsTable(): JSX.Element {
  const [page, setPage] = useState(0);
  // null until the user picks one: the backend's default period.
  const [chosenDays, setChosenDays] = useState<number | null>(null);
  const records = useNdaRecords(page, PAGE_SIZE, true, chosenDays);
  const items = records.data?.items ?? [];
  const total = records.data?.total ?? 0;
  const days = records.data?.days ?? chosenDays;
  // The options come from the first answer's default and maximum, which
  // don't change with the period chosen. Kept in state (set during render,
  // once) so later answers, and placeholder data while one loads, can't
  // change the list under the user.
  const [limits, setLimits] = useState<{ defaultDays: number | null; maxDays: number | null } | null>(null);
  if (limits === null && records.data && !records.isPlaceholderData) {
    setLimits({ defaultDays: records.data.days, maxDays: records.data.maxDays });
  }
  const options = limits ? periodOptions(limits.defaultDays, limits.maxDays) : [];
  const period = days === null ? "" : days === 1 ? "in the last day" : `in the last ${days} days`;

  if (records.isError && !records.data) {
    return (
      <ErrorNotice error={records.error} onRetry={() => void records.refetch()} retrying={records.isFetching}>
        Couldn&apos;t load the NDA records.
      </ErrorNotice>
    );
  }

  return (
    <Stack spacing={1.5}>
      <Stack direction="row" spacing={2} sx={{ alignItems: "center", flexWrap: "wrap" }}>
        {options.length > 1 && days !== null && (
          <TextField
            select
            size="small"
            label="Period"
            value={days}
            onChange={(e) => {
              setChosenDays(Number(e.target.value));
              setPage(0);
            }}
            sx={{ minWidth: 160 }}
          >
            {options.map((d) => (
              <MenuItem key={d} value={d}>
                {periodLabel(d)}
              </MenuItem>
            ))}
          </TextField>
        )}
        {period && (
          <Typography variant="body2" color="text.secondary">
            NDAs generated {period}, newest first.
          </Typography>
        )}
      </Stack>
      <TableContainer component={Paper} variant="outlined">
        <Table size="small" aria-label="Generated NDAs">
          <TableHead>
            <TableRow>
              <TableCell sx={{ fontWeight: 700, whiteSpace: "nowrap" }}>Generated</TableCell>
              <TableCell sx={{ fontWeight: 700 }}>Generated by</TableCell>
              <TableCell sx={{ fontWeight: 700 }}>Counterparty</TableCell>
              <TableCell sx={{ fontWeight: 700 }}>WSO2 Company</TableCell>
              <TableCell sx={{ fontWeight: 700 }}>Source</TableCell>
            </TableRow>
          </TableHead>
          <TableBody>
            {records.isPending && (
              <TableRow>
                <TableCell colSpan={5} align="center" sx={{ py: 4 }}>
                  <CircularProgress size={22} aria-label="Loading NDA records" />
                </TableCell>
              </TableRow>
            )}
            {!records.isPending && items.length === 0 && (
              <TableRow>
                <TableCell colSpan={5} align="center" sx={{ py: 4 }}>
                  <Typography variant="body2" color="text.secondary">
                    {period ? `No NDAs have been generated ${period}.` : "No NDAs have been generated yet."}
                  </Typography>
                </TableCell>
              </TableRow>
            )}
            {items.map((r) => (
              <TableRow key={r.id}>
                <TableCell sx={{ whiteSpace: "nowrap" }}>{new Date(r.generatedAt).toLocaleString()}</TableCell>
                <TableCell>{r.generatedByEmail}</TableCell>
                <TableCell>
                  <Typography variant="body2">{r.counterpartyName}</Typography>
                  <Typography variant="caption" color="text.secondary">
                    {r.counterpartyAddress}
                  </Typography>
                </TableCell>
                <TableCell sx={{ whiteSpace: "nowrap" }}>{entityLabel(r.wso2Entity)}</TableCell>
                <TableCell>
                  <Chip
                    size="small"
                    variant="outlined"
                    label={r.source === "salesforce" ? "Salesforce" : "Manual entry"}
                  />
                </TableCell>
              </TableRow>
            ))}
          </TableBody>
        </Table>
        {total > 0 && (
          <TablePagination
            component="div"
            count={total}
            page={page}
            rowsPerPage={PAGE_SIZE}
            rowsPerPageOptions={[PAGE_SIZE]}
            onPageChange={(_, p) => setPage(p)}
          />
        )}
      </TableContainer>
    </Stack>
  );
}
