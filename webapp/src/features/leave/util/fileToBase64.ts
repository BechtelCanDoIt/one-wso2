// A file's bytes as plain base64 text, with no `data:` prefix: the form the
// leave backend takes a sick note in. The browser does the encoding: a data
// URL is `data:<type>;base64,<text>`, so the text is everything after the
// first comma.
export function fileToBase64(file: Blob): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const dataUrl = String(reader.result);
      resolve(dataUrl.slice(dataUrl.indexOf(",") + 1));
    };
    reader.onerror = () => reject(reader.error ?? new Error("The file could not be read."));
    reader.readAsDataURL(file);
  });
}
